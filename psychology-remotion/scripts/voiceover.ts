// Writes voiceover-script-ar.md and voiceover-guide.srt from src/voiceover.ts: npm run vo
import {writeFileSync} from 'node:fs';
import {VO} from '../src/voiceover';

const sec = (f: number) => f / 30;
const ts = (f: number) => {
  const ms = Math.round(sec(f) * 1000);
  const h = Math.floor(ms / 3600000);
  const m = Math.floor((ms % 3600000) / 60000);
  const s = Math.floor((ms % 60000) / 1000);
  const r = ms % 1000;
  return `${String(h).padStart(2, '0')}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')},${String(r).padStart(3, '0')}`;
};
const mmss = (f: number) => `0:${sec(f).toFixed(1).padStart(4, '0')}`;
// one flowing paragraph: a comma after single words so TTS pauses between them, and "... ..." joins collapsed
const paragraph = (parts: string[]) =>
  parts
    .map((t) => (/[.!؟?…،]$/u.test(t) ? t : `${t}،`))
    .join(' ')
    .replace(/\.\.\. \.\.\./g, '... ')
    .replace(/\s+/g, ' ')
    .trim();

// sanity: lines must not overlap and must stay inside 45 s
VO.forEach((l, i) => {
  if (l.end <= l.at) throw new Error(`line ${i} ends before it starts`);
  if (i > 0 && l.at < VO[i - 1].end) throw new Error(`line ${i} (${l.text}) overlaps the previous line`);
});

const srt = VO.map((l, i) => `${i + 1}\n${ts(l.at)} --> ${ts(l.end)}\n${l.voiced}\n`).join('\n');
writeFileSync('voiceover-guide.srt', srt);

const md: string[] = [];
md.push('# النص الصوتي (Arabic voiceover script)');
md.push('');
md.push('Generated by `npm run vo` from `src/voiceover.ts`. Every line uses **exactly the words on screen**, timed to the moment they appear. The "Read" column adds tashkeel on the words AI voices tend to misread; the words themselves are unchanged. The video contains no spoken numbers. The HUD heart rate («١٤٠») is a visual only; if you choose to voice it, say «مئة وأربعون».');
md.push('');
md.push('Not voiced on purpose: the reverse emotion flashes during the rewind (0:03-0:04.5, too fast to speak), the HUD labels («النبض»، «خوف»، «طمع»), the replay labels and pins («الجمهور»، «شراء»، «بيع»), and in the outro the «MIRAN GOLD» wordmark, the «Join on Telegram» button and the disclaimer. The outro is in English, so its line is read in English, as on screen (as in the other Miran Gold reels).');
md.push('');
md.push('Delivery: low, intimate and unhurried, like a thought rather than an advert. The single words on the ride are short and full of feeling. Leave the pauses: the summit (0:12.7-0:14.9) and the bottom (0:19.6-0:22) are meant to breathe.');
md.push('');
md.push('| # | Start | End | On screen | Read (with tashkeel) | Direction |');
md.push('|---:|---:|---:|---|---|---|');
VO.forEach((l, i) => md.push(`| ${i + 1} | ${mmss(l.at)} | ${mmss(l.end)} | ${l.text} | ${l.voiced} | ${l.note ?? ''} |`));
md.push('');
md.push('## As one paragraph (no timestamps)');
md.push('');
md.push('With tashkeel, for an AI voice:');
md.push('');
md.push(paragraph(VO.map((l) => l.voiced)));
md.push('');
md.push('Plain, exactly as on screen:');
md.push('');
md.push(paragraph(VO.map((l) => l.text)));
md.push('');
md.push('## Recording notes');
md.push('');
md.push('- Export as `public/voiceover.mp3`, starting at 0:00 (the first word, «ذعر», lands at 0:00.1). The music ducks automatically when the file exists.');
md.push('- `voiceover-guide.srt` is a guide track: import it into your editor or TTS tool to place each line.');
md.push('- If an AI voice still stumbles, try the word fully vowelled as in the "Read" column, or split the line at the "...".');
md.push('');
writeFileSync('voiceover-script-ar.md', md.join('\n'));
console.log(`voiceover-script-ar.md, voiceover-guide.srt (${VO.length} lines)`);
