// Writes sfx-cues.md from src/config.ts (AUDIO) and the heart-rate timeline: npm run cues
import {writeFileSync} from 'node:fs';
import {AUDIO, VIDEO} from '../src/config';
import {BEAT_FRAMES, BPM} from '../src/lib/director';

const tc = (f: number) => {
  const s = f / VIDEO.fps;
  return `${Math.floor(s / 60)}:${(s % 60).toFixed(2).padStart(5, '0')}`;
};
const L: string[] = [];
L.push('# Sound cue sheet');
L.push('');
L.push('Generated by `npm run cues` from `src/config.ts` (`AUDIO`). Edit the config, not this file.');
L.push(`Timeline: 30 fps, ${VIDEO.durationInFrames} frames (45 s). Every file is optional: drop it into \`public/\` (or \`public/sfx/\`) with the exact name and it is picked up on the next render.`);
L.push('');
L.push('## Sound effects');
L.push('');
L.push('| Frame | Time | File | Volume | Length | What happens |');
L.push('|---:|---:|---|---:|---|---|');
for (const c of [...AUDIO.sfx].sort((a, b) => a.frame - b.frame)) {
  const len = c.loopUntil ? `loops to frame ${c.loopUntil} (${tc(c.loopUntil)})` : 'one shot';
  L.push(`| ${c.frame} | ${tc(c.frame)} | \`${c.file}\` | ${c.volume} | ${len} | ${c.note} |`);
}
L.push('');
L.push('## Heartbeat (`sfx/heartbeat.mp3`)');
L.push('');
L.push('One short "lub-dub" (under 0.4 s). It is triggered on **every beat of the HUD heart-rate counter**, so the sound speeds up and slows down exactly with the on-screen number, louder when the pulse races. That is more precise than one looped file with a fixed rate: Remotion cannot change an audio file\'s speed over time.');
L.push('');
const beats = BEAT_FRAMES.filter((f) => f < AUDIO.heartbeat.until);
L.push(`${beats.length} beats until frame ${AUDIO.heartbeat.until}:`);
L.push('');
L.push('| Section | Frames | Heart rate (bpm) | Beat frames |');
L.push('|---|---|---|---|');
const sections: [string, number, number][] = [
  ['Cold open', 0, 90], ['Rewind', 90, 150], ['Question', 150, 240], ['Climb', 240, 380], ['Summit (hang time)', 380, 446],
  ['Drop', 446, 588], ['Bottom', 588, 664], ['Recovery', 664, 750], ['Reveal to lesson', 750, 1200],
];
for (const [name, a, b] of sections) {
  const bs = beats.filter((f) => f >= a && f < b);
  const lo = Math.round(Math.min(...BPM.slice(a, b)));
  const hi = Math.round(Math.max(...BPM.slice(a, b)));
  L.push(`| ${name} | ${a}-${b} | ${lo === hi ? lo : `${lo}-${hi}`} | ${bs.join(', ')} |`);
}
L.push('');
L.push('## Music (`music.mp3`)');
L.push('');
L.push(`- Loops for the whole video. Fades in over ${AUDIO.musicFadeInFrames} frames and out over the last ${AUDIO.musicFadeOutFrames} frames (${AUDIO.musicFadeOutFrames / 30} s).`);
L.push(`- Level ${AUDIO.musicVolume}; drops to ${AUDIO.musicVolumeUnderVoice} automatically when \`voiceover.mp3\` exists.`);
for (const d of AUDIO.musicDucks) {
  L.push(`- Ducked to ${Math.round(d.level * 100)}% from frame ${d.from} (${tc(d.from)}) to ${d.to} (${tc(d.to)}), ${d.ramp}-frame ramps${d.level < 0.1 ? ': the near-silence at the summit' : ': the quiet bottom'}.`);
}
L.push('');
L.push('## What to source');
L.push('');
L.push('| File | Character |');
L.push('|---|---|');
const what: Record<string, string> = {
  'sfx/impact.mp3': 'Deep cinematic hit with a short tail (boom + crack). Used for the crash, the drop, pins.',
  'sfx/alarm.mp3': 'Loopable alarm / klaxon bed, not too shrill (it sits under text). Fades in and out automatically.',
  'sfx/whoosh.mp3': 'Short air whoosh (0.4-0.8 s) for transitions and words slamming in.',
  'sfx/rewind.mp3': 'Tape-stop into a fast tape rewind (about 1.7 s).',
  'sfx/riser.mp3': 'Tension riser that builds for about 4.5 s and stops dead at the summit.',
  'sfx/sub-drop.mp3': 'Sub-bass drop / low boom for hitting the bottom.',
  'sfx/piano.mp3': 'One soft, warm piano note or chord with a long tail (hope).',
  'sfx/shine.mp3': 'Bright shimmer / sparkle for the logo shine.',
  'sfx/heartbeat.mp3': 'One clean "lub-dub", under 0.4 s, no reverb tail.',
  'music.mp3': 'Dark, cinematic, minimal bed (pulse + pads), 90-110 bpm, that survives being ducked to silence at 0:12.7.',
  'voiceover.mp3': 'See voiceover-script-ar.md. Starts at frame 0.',
};
for (const [f, d] of Object.entries(what)) L.push(`| \`${f}\` | ${d} |`);
L.push('');
writeFileSync('sfx-cues.md', L.join('\n'));
console.log('sfx-cues.md');
