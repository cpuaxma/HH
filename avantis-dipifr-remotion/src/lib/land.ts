const inside = (lon: number, lat: number, poly: Poly) => {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i];
    const [xj, yj] = poly[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};

export const isLand = (lon: number, lat: number) => {
  if (lat < -71) return true; // Antarctica
  if (!LAND.some((p) => inside(lon, lat, p))) return false;
  return !LAKES.some((p) => inside(lon, lat, p));
};

/** Dot spacing in degrees of latitude. */
export const DOT_STEP = 1.0;

let dots: [number, number][] | null = null;

/** [lon, lat] of every land dot: rows of equal latitude, evenly spaced along each row. */
export const getLandDots = () => {
  if (dots) return dots;
  const out: [number, number][] = [];
  for (let lat = -88 + DOT_STEP / 2; lat < 88; lat += DOT_STEP) {
    const count = Math.max(1, Math.round((360 * Math.cos((lat * Math.PI) / 180)) / DOT_STEP));
    // Stagger alternate rows by half a step so the pattern reads as a soft halftone.
    const row = Math.round((lat + 88) / DOT_STEP);
    const offset = (row % 2) * 0.5;
    for (let k = 0; k < count; k++) {
      const lon = -180 + ((k + offset) * 360) / count;
      if (isLand(lon, lat)) out.push([lon, lat]);
    }
  }
  dots = out;
  return out;
};
