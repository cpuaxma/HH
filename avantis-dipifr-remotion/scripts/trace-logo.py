"""Traces assets/avantis-logo.jpg into crisp vector paths for the end card.

Writes src/lib/logoTrace.ts with one SVG path per logo layer, so each can
animate on its own while together they reproduce the logo exactly:
  SHIELD_FILL  the shield's silhouette (drawn white: it is the white "A")
  SHIELD       the navy shield with the "A" cut out of it
  LAUREL_LEFT / LAUREL_RIGHT   the grey laurel branches
  WORDMARK     the navy "AVANTIS"
  TAGLINE      the grey "STRIVE TOWARDS EXCELLENCE"
plus LOGO_VIEWBOX (a crop of the 500px artboard around the artwork) and the
colours sampled from the logo (LOGO_COLORS), which src/data.ts uses.

Needs: pip install potracer numpy pillow
Usage: python3 scripts/trace-logo.py assets/avantis-logo.jpg src/lib/logoTrace.ts
"""
import json
import sys

import numpy as np
import potrace
from PIL import Image, ImageDraw, ImageFilter

src, out = sys.argv[1], sys.argv[2]
SCALE = 4  # trace a smooth 4x upscale: the source is a small JPEG
base = Image.open(src).convert('RGB')
W0, H0 = base.size
im = base.resize((W0 * SCALE, H0 * SCALE), Image.LANCZOS).filter(ImageFilter.GaussianBlur(1.2))
a = np.asarray(im).astype(float)
R, G, B = a[..., 0], a[..., 1], a[..., 2]
lum = 0.299 * R + 0.587 * G + 0.114 * B
# Hue: navy keeps a strong blue cast even where anti-aliased against white; grey has none.
blueness = (B - R) / (256 - lum)
is_navy_hue = blueness > 0.15

# Sample the exact colours from the logo's solid interiors (eroded, at 1x).
a0 = np.asarray(base).astype(int)
r0, g0, b0 = a0[..., 0], a0[..., 1], a0[..., 2]
def erode(m, s):
    return np.asarray(Image.fromarray((m * 255).astype(np.uint8)).filter(ImageFilter.MinFilter(s))) > 0
navy0 = erode((b0 - r0 > 40) & (r0 < 80), 5)
grey0 = erode((abs(r0 - g0) < 14) & (abs(g0 - b0) < 14) & (r0 < 150), 3)
hexc = lambda px: '#%02X%02X%02X' % tuple(int(v) for v in np.median(px, axis=0))
NAVY, GREY = hexc(a0[navy0]), hexc(a0[grey0])

# Threshold each colour halfway between it and the white background.
navy_lum = 0.299 * int(NAVY[1:3], 16) + 0.587 * int(NAVY[3:5], 16) + 0.114 * int(NAVY[5:7], 16)
grey_lum = 0.299 * int(GREY[1:3], 16) + 0.587 * int(GREY[3:5], 16) + 0.114 * int(GREY[5:7], 16)
# The wordmark sits on a soft grey drop shadow, which dulls the blue of its edge
# pixels: judge the hue over a small neighbourhood so the letter edges stay clean.
def dilate(m, s):
    return np.asarray(Image.fromarray((m * 255).astype(np.uint8)).filter(ImageFilter.MaxFilter(s))) > 0
navy = dilate(is_navy_hue & (lum < (navy_lum + 255) / 2), 9) & (lum < (navy_lum + 255) / 2)
grey = ~navy & ~is_navy_hue & (lum < (grey_lum + 255) / 2)

ys = np.arange(H0 * SCALE)[:, None]
xs = np.arange(W0 * SCALE)[None, :]
SPLIT_Y = 340 * SCALE      # between the shield/laurels and the wordmark
TAG_Y = 402 * SCALE        # between the wordmark and the tagline
MID_X = 250 * SCALE        # between the two laurel branches
shield = navy & (ys < SPLIT_Y)
wordmark = navy & (ys >= SPLIT_Y)
laurel = grey & (ys < SPLIT_Y)
tagline = grey & (ys >= TAG_Y)

# The shield's silhouette: everything the outside can't reach without crossing navy.
outside = Image.fromarray(((~shield) * 255).astype(np.uint8)).copy()  # copy: fromarray shares read-only memory
ImageDraw.floodfill(outside, (0, 0), 128)
shield_fill = np.asarray(outside) != 128


def to_path(mask, turdsize=12):
    # potracer traces the False pixels, so pass the inverse.
    bmp = potrace.Bitmap(~mask)
    plist = bmp.trace(turdsize=turdsize, alphamax=1.0, opticurve=True, opttolerance=0.2)
    parts = []
    for curve in plist:
        s = curve.start_point
        d = [f'M{s.x / SCALE:.2f} {s.y / SCALE:.2f}']
        for seg in curve.segments:
            if seg.is_corner:
                d.append(f'L{seg.c.x / SCALE:.2f} {seg.c.y / SCALE:.2f}L{seg.end_point.x / SCALE:.2f} {seg.end_point.y / SCALE:.2f}')
            else:
                d.append(
                    f'C{seg.c1.x / SCALE:.2f} {seg.c1.y / SCALE:.2f} {seg.c2.x / SCALE:.2f} {seg.c2.y / SCALE:.2f} '
                    f'{seg.end_point.x / SCALE:.2f} {seg.end_point.y / SCALE:.2f}'
                )
        d.append('Z')
        parts.append(''.join(d))
    return ''.join(parts)


def bbox(mask):
    yy, xx = np.where(mask)
    return [round(float(v) / SCALE, 1) for v in (xx.min(), yy.min(), xx.max(), yy.max())]


layers = {
    'SHIELD_FILL': shield_fill,
    'SHIELD': shield,
    'LAUREL_LEFT': laurel & (xs < MID_X),
    'LAUREL_RIGHT': laurel & (xs >= MID_X),
    'WORDMARK': wordmark,
    'TAGLINE': tagline,
}
paths = {k: to_path(m, 4 if k == 'TAGLINE' else 12) for k, m in layers.items()}
x0, y0, x1, y1 = bbox(navy | grey)
pad = 6
with open(out, 'w') as f:
    f.write('// Generated by scripts/trace-logo.py from assets/avantis-logo.jpg. Do not edit by hand.\n')
    f.write('// Coordinates are in the 500px logo artboard. Draw paths with fill-rule "evenodd".\n\n')
    f.write(f'export const LOGO_VIEWBOX = {json.dumps([x0 - pad, y0 - pad, round(x1 - x0 + 2 * pad, 1), round(y1 - y0 + 2 * pad, 1)])};\n\n')
    f.write(f'/** Colours sampled from the logo. */\nexport const LOGO_COLORS = {{navy: {json.dumps(NAVY)}, grey: {json.dumps(GREY)}}};\n\n')
    f.write('/** Bounding boxes [x0, y0, x1, y1] of each layer, for animation pivots. */\n')
    f.write(f'export const LOGO_BOXES = {json.dumps({k: bbox(m) for k, m in layers.items()})};\n\n')
    for k, d in paths.items():
        f.write(f'export const {k} =\n  {json.dumps(d)};\n\n')
print('colours', NAVY, GREY)
print('viewbox', x0, y0, x1, y1)
for k, d in paths.items():
    print(k, len(d), 'chars', layers[k].sum() // (SCALE * SCALE), 'px')
