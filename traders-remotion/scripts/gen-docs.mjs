// Generates the docs that must stay in sync with the code:
//   sfx-cues.md            every sound cue with its frame/time (from src/audio/cues.ts)
//   voiceover-guide-ar.srt the voiceover guide track (from src/audio/voiceover.ts)
//   counter-check.md       standing pillars vs counter after every trap (from src/arena/plan.ts)
// It compiles the TypeScript modules with esbuild and runs them in Node.
//   node scripts/gen-docs.mjs
import {build} from 'esbuild';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const entry = `
export {getCues} from './src/audio/cues';
export {VO} from './src/audio/voiceover';
export {PLAN, standingAt, counterValue} from './src/arena/plan';
export {TRAPS, COUNTER_STEPS, AUDIO, VIDEO} from './src/config';
`;
const out = path.resolve(`node_modules/.cache/traders-docs-${process.pid}.mjs`);
fs.mkdirSync(path.dirname(out), {recursive: true});
await build({stdin: {contents: entry, resolveDir: process.cwd(), loader: 'ts'}, bundle: true, platform: 'node', format: 'esm', outfile: out, logLevel: 'error', external: ['react', 'react-dom']});
const m = await import(out);
fs.unlinkSync(out);

const fps = m.VIDEO.fps;
const tc = (f) => {
  const s = f / fps;
  return `${String(Math.floor(s / 60)).padStart(2, '0')}:${(s % 60).toFixed(2).padStart(5, '0')}`;
};
const srt = (f) => {
  const ms = Math.round((f / fps) * 1000);
  const h = Math.floor(ms / 3600000);
  const mi = Math.floor((ms % 3600000) / 60000);
  const se = Math.floor((ms % 60000) / 1000);
  return `${String(h).padStart(2, '0')}:${String(mi).padStart(2, '0')}:${String(se).padStart(2, '0')},${String(ms % 1000).padStart(3, '0')}`;
};

// ── sfx-cues.md ──
const cues = m.getCues();
let md = `# Sound cue sheet\n\nGenerated by \`node scripts/gen-docs.mjs\` from \`src/audio/cues.ts\`. 30 fps, 1200 frames.\nEvery file is optional: a cue plays only if \`public/sfx/<name>.mp3\` exists. Volumes are multiplied by \`AUDIO.sfxVolume\` (${m.AUDIO.sfxVolume}).\n\n`;
md += `| Frame | Time | File | Vol | What happens |\n|---:|---:|---|---:|---|\n`;
cues.forEach((c) => (md += `| ${c.at} | ${tc(c.at)} | \`sfx/${c.file}.mp3\` | ${c.volume.toFixed(2)} | ${c.note} |\n`));
md += `\n## Music and voiceover\n\n| Slot | File | Behaviour |\n|---|---|---|\n`;
md += `| Music | \`public/${m.AUDIO.music}\` | Starts at frame 0 at ${m.AUDIO.musicVolume}. Ducks to ${m.AUDIO.musicDuck} under each voiceover line (only if a voiceover file exists). Swells warm to ${m.AUDIO.musicSwell} for the survivors (frames 836–1040). Fades out over the last ${m.AUDIO.fadeOutFrames} frames (2 s). |\n`;
md += `| Voiceover | \`public/${m.AUDIO.voiceover}\` | Starts at frame 0. Record it to the timings in \`voiceover-script-ar.md\` / \`voiceover-guide-ar.srt\`. |\n`;
fs.writeFileSync('sfx-cues.md', md);

// ── voiceover-guide-ar.srt ──
const lines = m.VO.map((l, i) => `${i + 1}\n${srt(l.from)} --> ${srt(l.to)}\n${l.spoken}\n`);
fs.writeFileSync('voiceover-guide-ar.srt', lines.join('\n'));

// ── counter-check.md ──
let cc = `# Counter check\n\nGenerated by \`node scripts/gen-docs.mjs\`. The counter is computed from the same death frames that drive the pillars, so it always equals the number of pillars still standing.\n\n| Trap | Mechanism | Removes | Window (frames) | Counter hit | Standing after | Configured |\n|---|---|---:|---|---:|---:|---:|\n`;
m.PLAN.traps.forEach((t, k) => {
  const after = m.standingAt(t.start + t.len);
  cc += `| ${k + 1}. ${t.def.title.replace('\n', ' ')} | ${t.def.mechanism} | ${t.def.remove} | ${t.start}–${t.start + t.len} | ${t.hit} | ${after} | ${m.COUNTER_STEPS[k + 1]} ${after === m.COUNTER_STEPS[k + 1] ? '✓' : '✗'} |\n`;
});
let mism = 0;
for (let f = 0; f < 1200; f++) if (Math.round(m.counterValue(f)) !== m.standingAt(f)) mism++;
cc += `\nFrames (of 1200) where the number the counter shows (its rolling value, rounded) differs from the pillars still standing: **${mism}**. The counter's whole number is the standing count by construction; each loss only adds a short rolling animation (under half a digit) to the digits.\n`;
fs.writeFileSync('counter-check.md', cc);
console.log(`sfx-cues.md (${cues.length} cues), voiceover-guide-ar.srt (${m.VO.length} lines), counter-check.md (${mism} mismatching frames)`);
